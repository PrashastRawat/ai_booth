import { DatabaseSync } from "node:sqlite";
import fs from "node:fs";
import path from "node:path";

// SQLite file lives in ./data so it survives restarts. Created on first use.
const DB_PATH = path.join(process.cwd(), "data", "entries.db");

const globalForDb = globalThis as unknown as { __entriesDb?: DatabaseSync };

function openDatabase(): DatabaseSync {
  fs.mkdirSync(path.dirname(DB_PATH), { recursive: true });
  const db = new DatabaseSync(DB_PATH);
  db.exec(`
    PRAGMA journal_mode = WAL;
    PRAGMA busy_timeout = 3000;

    CREATE TABLE IF NOT EXISTS entries (
      id          TEXT PRIMARY KEY,              -- UUID generated by the worker; prevents duplicate inserts
      occurred_at INTEGER NOT NULL,              -- epoch milliseconds when the line was crossed
      track_id    INTEGER,                       -- ByteTrack ID (for debugging only)
      received_at INTEGER NOT NULL               -- epoch milliseconds when the API stored it
    );
    CREATE INDEX IF NOT EXISTS idx_entries_occurred_at ON entries (occurred_at);

    CREATE TABLE IF NOT EXISTS worker_status (
      id               INTEGER PRIMARY KEY CHECK (id = 1),  -- single row, updated by heartbeats
      camera_connected INTEGER NOT NULL,
      fps              REAL NOT NULL,
      session_entries  INTEGER NOT NULL,
      updated_at       INTEGER NOT NULL
    );
  `);
  // Added after the first release: whether frames are usable (not black/stalled).
  const columns = db.prepare("PRAGMA table_info(worker_status)").all() as { name: string }[];
  if (!columns.some((c) => c.name === "feed_ok")) {
    db.exec("ALTER TABLE worker_status ADD COLUMN feed_ok INTEGER NOT NULL DEFAULT 1");
  }
  return db;
}

export function getDb(): DatabaseSync {
  if (!globalForDb.__entriesDb) {
    globalForDb.__entriesDb = openDatabase();
  }
  return globalForDb.__entriesDb;
}
