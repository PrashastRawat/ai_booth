import { DatabaseSync } from "node:sqlite";
import fs from "node:fs";
import path from "node:path";

// SQLite file lives in ./data so it survives restarts. Created on first use.
const DB_PATH = path.join(process.cwd(), "data", "entries.db");

const globalForDb = globalThis as unknown as { __entriesDb?: DatabaseSync };

/**
 * Creates tables and indexes if missing and applies additive migrations.
 * Idempotent and non-destructive: it never deletes or rewrites existing entries.
 */
export function initSchema(db: DatabaseSync): void {
  db.exec(`
    PRAGMA journal_mode = WAL;
    PRAGMA busy_timeout = 3000;

    CREATE TABLE IF NOT EXISTS entries (
      id          TEXT PRIMARY KEY,              -- UUID generated by the worker; prevents duplicate inserts
      occurred_at INTEGER NOT NULL,              -- epoch milliseconds (UTC) when the line was crossed
      track_id    INTEGER,                       -- ByteTrack ID (for debugging only)
      received_at INTEGER NOT NULL               -- epoch milliseconds (UTC) when the API stored it
    );
    CREATE INDEX IF NOT EXISTS idx_entries_occurred_at ON entries (occurred_at);

    CREATE TABLE IF NOT EXISTS camera_status (
      name             TEXT PRIMARY KEY,            -- camera name from worker config (A, B, ...)
      connected        INTEGER NOT NULL,
      feed_ok          INTEGER NOT NULL,            -- 0 while frames are black/stalled
      fps              REAL NOT NULL,
      session_entries  INTEGER NOT NULL,
      updated_at       INTEGER NOT NULL
    );

    CREATE TABLE IF NOT EXISTS worker_status (
      id               INTEGER PRIMARY KEY CHECK (id = 1),  -- single row, updated by heartbeats
      camera_connected INTEGER NOT NULL,
      fps              REAL NOT NULL,
      session_entries  INTEGER NOT NULL,
      updated_at       INTEGER NOT NULL
    );
  `);
  // Migration: entries made before multi-camera support belong to camera "A".
  const entryColumns = db.prepare("PRAGMA table_info(entries)").all() as { name: string }[];
  if (!entryColumns.some((c) => c.name === "camera")) {
    db.exec("ALTER TABLE entries ADD COLUMN camera TEXT NOT NULL DEFAULT 'A'");
  }
  // Covering index for per-camera time-range counts (today, total, per-day reports):
  // each count is answered from the index alone without touching table rows, and the
  // list of cameras is found with an index skip-scan. Measured on 5 lakh rows:
  // ~35 ms for all counts versus ~190 ms for GROUP BY camera over the time index.
  db.exec("CREATE INDEX IF NOT EXISTS idx_entries_camera_occurred ON entries (camera, occurred_at)");
}

function openDatabase(): DatabaseSync {
  fs.mkdirSync(path.dirname(DB_PATH), { recursive: true });
  const db = new DatabaseSync(DB_PATH);
  initSchema(db);
  return db;
}

export function getDb(): DatabaseSync {
  if (!globalForDb.__entriesDb) {
    globalForDb.__entriesDb = openDatabase();
  }
  return globalForDb.__entriesDb;
}
